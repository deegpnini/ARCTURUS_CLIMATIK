import argparse
import json
import sqlite3
import sys
from pathlib import Path

BASE = Path(__file__).resolve().parents[2]
if str(BASE) not in sys.path:
    sys.path.insert(0, str(BASE))

from src.relatorios.postgres_db import get_postgres_connection


SQLITE_PATH = BASE / "data" / "arcturus.db"
GEOJSON_PATH = BASE / "cache" / "mancha_2019.geojson"
QC_VALUES = {"VALIDO", "SUSPEITO", "CORROMPIDO", "MANUAL"}


def create_schema(connection):
    with connection.cursor() as cursor:
        cursor.execute("CREATE EXTENSION IF NOT EXISTS postgis")
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS leituras (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL,
                cota_cm DOUBLE PRECISION,
                vz_cm_h DOUBLE PRECISION,
                az_cm_h2 DOUBLE PRECISION,
                regime TEXT,
                chuva_pior_caso_mm DOUBLE PRECISION,
                confianca_score INTEGER,
                qc TEXT NOT NULL DEFAULT 'VALIDO'
                    CHECK (qc IN ('VALIDO', 'SUSPEITO', 'CORROMPIDO', 'MANUAL'))
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS inundacoes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source TEXT NOT NULL,
                source_id TEXT NOT NULL,
                geom geometry(Polygon, 4326) NOT NULL,
                UNIQUE (source, source_id)
            )
        """)
        cursor.execute("""
            CREATE INDEX IF NOT EXISTS idx_inundacoes_geom
            ON inundacoes USING GIST (geom)
        """)


def migrar_leituras(sqlite_path, connection):
    with sqlite3.connect(sqlite_path) as source:
        columns = {
            row[1] for row in source.execute("PRAGMA table_info(leituras)")
        }
        if not columns:
            raise RuntimeError(f"A tabela leituras não existe em {sqlite_path}")

        source_fields = (
            "id",
            "timestamp",
            "cota_cm",
            "vz_cm_h",
            "az_cm_h2",
            "regime",
            "chuva_pior_caso_mm",
            "confianca_score",
            "qc",
        )
        selected_fields = [
            field for field in source_fields if field in columns
        ]
        rows = source.execute(
            f"SELECT {', '.join(selected_fields)} FROM leituras ORDER BY id"
        ).fetchall()

    field_positions = {field: index for index, field in enumerate(selected_fields)}
    insert_sql = """
        INSERT INTO leituras (
            id, timestamp, cota_cm, vz_cm_h, az_cm_h2, regime,
            chuva_pior_caso_mm, confianca_score, qc
        ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (id) DO NOTHING
    """
    inserted = 0
    with connection.cursor() as cursor:
        for row in rows:
            qc = row[field_positions["qc"]] if "qc" in field_positions else None
            qc = str(qc or "VALIDO").strip().upper()
            if qc not in QC_VALUES:
                raise ValueError(f"Flag QC inválida na leitura {row[field_positions['id']]}: {qc}")
            values = [
                row[field_positions[field]] if field in field_positions else None
                for field in source_fields
            ]
            values[8] = qc
            cursor.execute(insert_sql, values)
            inserted += cursor.rowcount

        cursor.execute("""
            SELECT setval(
                pg_get_serial_sequence('leituras', 'id'),
                GREATEST(COALESCE(MAX(id), 1), 1),
                COUNT(*) > 0
            )
            FROM leituras
        """)
    return len(rows), inserted


def carregar_features_geojson(geojson_path):
    with Path(geojson_path).open("r", encoding="utf-8") as file:
        document = json.load(file)

    if document.get("type") == "FeatureCollection":
        features = document.get("features", [])
    elif document.get("type") == "Feature":
        features = [document]
    else:
        raise ValueError("O GeoJSON deve ser uma Feature ou FeatureCollection.")

    prepared = []
    for index, feature in enumerate(features):
        geometry = feature.get("geometry") or {}
        if geometry.get("type") != "Polygon":
            raise ValueError(
                f"Feature {index} não é Polygon: {geometry.get('type') or 'sem geometria'}"
            )
        source_id = str(feature.get("id", index))
        prepared.append((source_id, json.dumps(geometry)))
    if not prepared:
        raise ValueError("O GeoJSON não contém polígonos para importar.")
    return prepared


def importar_inundacoes(geojson_path, connection):
    features = carregar_features_geojson(geojson_path)
    with connection.cursor() as cursor:
        for source_id, geometry_json in features:
            cursor.execute("""
                INSERT INTO inundacoes (source, source_id, geom)
                VALUES (%s, %s, ST_SetSRID(ST_GeomFromGeoJSON(%s), 4326))
                ON CONFLICT (source, source_id) DO NOTHING
            """, (Path(geojson_path).name, source_id, geometry_json))
    return len(features)


def verificar_consulta_espacial(connection):
    with connection.cursor() as cursor:
        cursor.execute("""
            SELECT COUNT(*)
            FROM inundacoes
            WHERE ST_Contains(
                geom,
                ST_SetSRID(ST_MakePoint(-49.0, -28.5), 4326)
            )
        """)
        return cursor.fetchone()[0]


def main():
    parser = argparse.ArgumentParser(
        description="Migra leituras SQLite para PostgreSQL/PostGIS."
    )
    parser.add_argument("--sqlite", type=Path, default=SQLITE_PATH)
    parser.add_argument("--geojson", type=Path, default=GEOJSON_PATH)
    parser.add_argument(
        "--skip-geojson",
        action="store_true",
        help="Cria a tabela espacial sem importar o polígono.",
    )
    args = parser.parse_args()

    connection = get_postgres_connection()
    try:
        create_schema(connection)
        total, inserted = migrar_leituras(args.sqlite, connection)
        connection.commit()
        print(f"Leituras SQLite: {total}; novas linhas PostgreSQL: {inserted}.")

        if args.skip_geojson:
            print("Importação GeoJSON ignorada por solicitação.")
        else:
            features = importar_inundacoes(args.geojson, connection)
            connection.commit()
            print(f"Features GeoJSON processadas: {features}.")

        matches = verificar_consulta_espacial(connection)
        print(f"Polígonos contendo (-49.0, -28.5): {matches}.")
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


if __name__ == "__main__":
    main()
